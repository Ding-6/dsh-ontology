function parseAttributes(spec) {
  if (spec === '' || spec === undefined) return []
  return spec.split('|').map(item => {
    const [name, rawType] = item.split(':')
    const type = (rawType ?? 'string').replace('!', '')
    return { name, type, required: (rawType ?? '').endsWith('!') }
  })
}

/** 生成一份可导入的本体台账（商企市场样例）。 */
export function seedOntology() {
  const objects = OBJECTS.map(([name, code, domain, description, attrs]) => ({
    name,
    code,
    domain,
    description,
    attributes: parseAttributes(attrs),
    status: 'approved',
    source: 'import',
  }))
  const relations = RELATIONS.map(([from, name, to, cardinality]) => ({
    name, from, to, cardinality, status: 'approved', source: 'import',
  }))
  const rules = RULES.map(([name, type, expression, scope]) => ({
    name, type, expression, scope, status: 'approved', source: 'import',
  }))
  const actions = ACTIONS.map(([name, kind, target, params, result]) => ({
    name, kind, target, result, params: parseAttributes(params), status: 'approved', source: 'import',
  }))
  return { objects, relations, rules, actions, services: [], updatedAt: Date.now() }
}

